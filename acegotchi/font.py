WIDTH = 5
HEIGHT = 7
ADVANCE = 6


def char_width(scale=1):
    return WIDTH * scale


def text_width(text, scale=1, spacing=1):
    if not text:
        return 0
    return (len(text) * (WIDTH + spacing) - spacing) * scale


def draw_text(buf, x, y, text, colour, scale=1, spacing=1, shadow=None):
    """Draw text into a PixBuf. Unknown glyphs render as blanks."""
    cx = x
    if shadow is not None:
        draw_text(buf, x + scale, y + scale, text, shadow, scale, spacing, None)
    for ch in text:
        g = GLYPHS.get(ch.upper()) or GLYPHS.get(ch)
        if g is not None:
            if scale == 1:
                buf.blit_art(g, cx, y, {"#": colour})
            else:
                for gy, row in enumerate(g):
                    for gx, c in enumerate(row):
                        if c == "#":
                            buf.rect(cx + gx * scale, y + gy * scale, scale, scale, colour)
        cx += (WIDTH + spacing) * scale
    return cx


def draw_text_right(buf, x_right, y, text, colour, scale=1, spacing=1, shadow=None):
    w = text_width(text, scale, spacing)
    draw_text(buf, x_right - w, y, text, colour, scale, spacing, shadow)


def draw_text_center(buf, cx, y, text, colour, scale=1, spacing=1, shadow=None):
    w = text_width(text, scale, spacing)
    draw_text(buf, cx - w // 2, y, text, colour, scale, spacing, shadow)



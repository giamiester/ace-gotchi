def draw_micro(buf, x, y, text, colour, spacing=1):
    cx = x
    for ch in text:
        g = MICRO.get(ch.upper()) or MICRO.get(ch)
        if g is not None:
            buf.blit_art(g, cx, y, {"#": colour})
        cx += 3 + spacing
    return cx


def micro_width(text, spacing=1):
    if not text:
        return 0
    return len(text) * (3 + spacing) - spacing
